"""Fake TriageProvider for SAST Triage Platform.

Provides a deterministic, local mock implementation of LLM triage logic
for testing and development without making network API calls.

Security & Integrity Guarantees:
- Never copies source code text, imports, decorators, absolute paths, or secret canaries into TriageDecision.
- Deterministic output based purely on explicit `prompt_type` signals and context availability.
- Does NOT use rule_id, file path, or severity heuristics to infer verdicts.
- Purely functional and side-effect free.
"""

from enum import Enum

from sast_triage.errors import SastTriageError
from sast_triage.models import (
    ModelConfidence,
    ModelVerdict,
    TriageDecision,
    TriageInput,
)


class FakeTriageProviderMode(str, Enum):
    """Execution modes for FakeTriageProvider."""

    NORMAL = "normal"
    RAISE_TIMEOUT = "raise_timeout"
    RAISE_PROVIDER_ERROR = "raise_provider_error"


class FakeTriageProvider:
    """Fake TriageProvider for deterministic testing."""

    def __init__(
        self,
        mode: FakeTriageProviderMode | str = FakeTriageProviderMode.NORMAL,
    ) -> None:
        if isinstance(mode, str):
            try:
                mode = FakeTriageProviderMode(mode.lower())
            except ValueError as exc:
                raise SastTriageError(
                    safe_message="Invalid mode specified for FakeTriageProvider.",
                    error_code="TRIAGE_INVALID_PROVIDER_MODE",
                    retryable=False,
                ) from exc
        elif not isinstance(mode, FakeTriageProviderMode):
            raise SastTriageError(
                safe_message="Invalid mode specified for FakeTriageProvider.",
                error_code="TRIAGE_INVALID_PROVIDER_MODE",
                retryable=False,
            )

        self._mode = mode

    @property
    def provider_name(self) -> str:
        """Return the stable provider identifier."""
        return "fake"

    @property
    def model_version(self) -> str:
        """Return the deterministic fake model identifier."""
        return "fake-triage-v1"

    @property
    def mode(self) -> FakeTriageProviderMode:
        """Return provider execution mode."""
        return self._mode

    def triage(self, triage_input: TriageInput) -> TriageDecision:
        """Produce a deterministic TriageDecision from a TriageInput.

        Args:
            triage_input: Validated TriageInput payload.

        Returns:
            A deterministic TriageDecision Pydantic model.

        Raises:
            SastTriageError: On invalid input, simulated timeout, or simulated provider error.
        """
        if not isinstance(triage_input, TriageInput):
            raise SastTriageError(
                safe_message="triage() requires a TriageInput instance.",
                error_code="TRIAGE_INVALID_INPUT",
                retryable=False,
            )

        # 1. Provider Failure Simulation Mode
        if self._mode == FakeTriageProviderMode.RAISE_TIMEOUT:
            raise SastTriageError(
                safe_message="FakeTriageProvider request timed out.",
                error_code="TRIAGE_PROVIDER_TIMEOUT",
                retryable=True,
            )

        if self._mode == FakeTriageProviderMode.RAISE_PROVIDER_ERROR:
            raise SastTriageError(
                safe_message="FakeTriageProvider encountered an internal provider error.",
                error_code="TRIAGE_PROVIDER_ERROR",
                retryable=False,
            )

        # 2. Context Unavailable Precedence
        if not triage_input.context.context_available:
            evidence = ["Source code context is unavailable."]
            if triage_input.context.missing_context_reasons:
                evidence.extend([r.value for r in triage_input.context.missing_context_reasons])

            return TriageDecision(
                model_verdict=ModelVerdict.NEEDS_REVIEW,
                model_confidence=ModelConfidence.LOW,
                summary="Deterministic fake manual-review decision.",
                evidence=evidence,
                missing_information=["Source code context"],
                assumptions=["Generated by FakeTriageProvider for testing only."],
                model_version="fake-triage-v1",
                prompt_version=triage_input.prompt_version,
            )

        # 3. Explicit prompt_type Test Signals
        prompt_type = triage_input.prompt_type.strip().lower()

        if prompt_type == "fake.tp.high":
            return TriageDecision(
                model_verdict=ModelVerdict.LIKELY_TP,
                model_confidence=ModelConfidence.HIGH,
                summary="Deterministic fake true-positive decision.",
                evidence=["Matched fake.tp.high test scenario."],
                missing_information=[],
                assumptions=["Generated by FakeTriageProvider for testing only."],
                model_version="fake-triage-v1",
                prompt_version=triage_input.prompt_version,
            )

        if prompt_type == "fake.fp.high":
            return TriageDecision(
                model_verdict=ModelVerdict.LIKELY_FP,
                model_confidence=ModelConfidence.HIGH,
                summary="Deterministic fake false-positive decision.",
                evidence=["Matched fake.fp.high test scenario."],
                missing_information=[],
                assumptions=["Generated by FakeTriageProvider for testing only."],
                model_version="fake-triage-v1",
                prompt_version=triage_input.prompt_version,
            )

        if prompt_type == "fake.review.low":
            return TriageDecision(
                model_verdict=ModelVerdict.NEEDS_REVIEW,
                model_confidence=ModelConfidence.LOW,
                summary="Deterministic fake manual-review decision.",
                evidence=["Matched fake.review.low test scenario."],
                missing_information=["Detailed manual audit needed."],
                assumptions=["Generated by FakeTriageProvider for testing only."],
                model_version="fake-triage-v1",
                prompt_version=triage_input.prompt_version,
            )

        # 4. Default Decision
        return TriageDecision(
            model_verdict=ModelVerdict.NEEDS_REVIEW,
            model_confidence=ModelConfidence.MEDIUM,
            summary="Deterministic fake default decision.",
            evidence=["Matched default fake test scenario."],
            missing_information=[],
            assumptions=["Generated by FakeTriageProvider for testing only."],
            model_version="fake-triage-v1",
            prompt_version=triage_input.prompt_version,
        )
